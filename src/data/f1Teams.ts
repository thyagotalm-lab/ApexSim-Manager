/**
 * Retorna a sigla oficial da F1 real (3 letras: RBR, FER, MCL, MER, AMR, ALP, WIL, RB, SAU, HAA, AUD, CAD)
 */
export const getTeamCode = (teamName: string, simulator?: string): string => {
  if (!teamName) return 'F1';
  const teams = getTeamsBySimulator(simulator || 'F1 25');
  const found = teams.find(
    (t) =>
      t.name.toLowerCase() === teamName.toLowerCase() ||
      t.shortName.toLowerCase() === teamName.toLowerCase() ||
      t.code.toLowerCase() === teamName.toLowerCase()
  );
  if (found) return found.code;

  // Normalização para F1 real
  const lower = teamName.toLowerCase();
  if (lower.includes('red bull') || lower.includes('oracle') || lower.includes('rbr')) return 'RBR';
  if (lower.includes('ferrari') || lower.includes('sf-') || lower.includes('scuderia')) return 'FER';
  if (lower.includes('mclaren') || lower.includes('mcl')) return 'MCL';
  if (lower.includes('mercedes') || lower.includes('amg')) return 'MER';
  if (lower.includes('aston martin') || lower.includes('aston') || lower.includes('amr')) return 'AMR';
  if (lower.includes('alpine') || lower.includes('bwt') || lower.includes('alp')) return 'ALP';
  if (lower.includes('williams') || lower.includes('wil')) return 'WIL';
  if (
    lower.includes('racing bulls') ||
    lower.includes('vcarb') ||
    lower.includes('cash app') ||
    lower.includes('toro rosso') ||
    lower.includes('alpha tauri') ||
    lower.includes('alphatauri')
  ) {
    return 'RB';
  }
  if (lower.includes('sauber') || lower.includes('kick') || lower.includes('stake') || lower.includes('alfa romeo')) {
    return 'SAU';
  }
  if (lower.includes('haas') || lower.includes('haa')) return 'HAA';
  if (lower.includes('audi')) return 'AUD';
  if (lower.includes('cadillac') || lower.includes('andretti')) return 'CAD';

  // SimRacing & GT Fallbacks
  if (lower.includes('porsche') || lower.includes('redline')) return 'POR';
  if (lower.includes('apex')) return 'APX';
  if (lower.includes('bmw') || lower.includes('wrt')) return 'BMW';
  if (lower.includes('lamborghini') || lower.includes('lynx')) return 'LAM';

  return teamName.replace(/[^A-Za-z0-9]/g, '').slice(0, 3).toUpperCase();
};
